import math

def grid(img): return [[1 if c == '#' else 0 for c in row] for row in img]

# Animacion de muerte: colapso "hacia arriba" recortando el disco base por
# angulo (semiapertura respecto al vector ARRIBA). D4 = chispa final en cruz.
def death_frames():
    base = grid(closed)
    frames = []
    for idx, semi in enumerate([45, 70, 90, 135, None]):
        g = [[0] * 16 for _ in range(16)]
        if semi is None:
            # D4: 4 puntos de 2x2 en cruz alrededor del centro, disco invisible
            for (r, c) in [(1, 7), (13, 7), (7, 1), (7, 13)]:
                for dr in range(2):
                    for dc in range(2):
                        g[r + dr][c + dc] = 1
        else:
            for r in range(16):
                for c in range(16):
                    if not base[r][c]:
                        continue
                    dx = c - 7.5
                    dy = r - 7.5
                    # 0 grados = arriba, 180 = abajo; se borra dentro de la cuna
                    ang = math.degrees(math.atan2(abs(dx), -dy))
                    if ang > semi:
                        g[r][c] = 1
        frames.append(("DEATH_D%d" % idx, g))
    return frames

